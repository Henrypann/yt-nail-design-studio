import assert from 'node:assert/strict';
import { CATALOGS } from '../src/lib/i18n/messages.ts';
import { toLocale } from '../src/lib/i18n/types.ts';
import { LOCALE_STORAGE_KEY, persistCanonicalLocale, readCanonicalLocale, syncDocumentLocale } from '../src/lib/i18n/locale.ts';
import { InMemoryMessageCatalogRepositoryV1 } from '../src/lib/i18n/repository.ts';
import { formatMessage } from '../src/lib/i18n/format.ts';
import { resolveMessage } from '../src/lib/i18n/resolve.ts';
import fs from 'node:fs';

const zh = Object.keys(CATALOGS['zh-CN'].messages).sort();
const en = Object.keys(CATALOGS['en-US'].messages).sort();
assert.deepEqual(en, zh, 'zh-CN/en-US catalogs must have exact key parity');
const placeholders = (value) => [...value.matchAll(/\{([a-zA-Z0-9_]+)\}/g)].map((match) => match[1]).sort();
for (const key of zh) assert.deepEqual(placeholders(CATALOGS['zh-CN'].messages[key]), placeholders(CATALOGS['en-US'].messages[key]), `placeholder parity failed for ${key}`);
assert.ok(zh.every((key) => !key.startsWith('legacy.') && !/^\w+\.[a-f0-9]{8,}$/.test(key)), 'catalog keys must be semantic, not legacy/hash keys');
assert.equal(toLocale('zh'), 'zh-CN'); assert.equal(toLocale('en'), 'en-US'); assert.equal(toLocale('en-US'), 'en-US');
assert.equal(readCanonicalLocale('zh'), 'zh-CN'); assert.equal(readCanonicalLocale('en'), 'en-US');
const persisted = new Map(); const storage = { setItem: (key, value) => persisted.set(key, value) };
assert.equal(persistCanonicalLocale('zh', storage), 'zh-CN'); assert.equal(persisted.get(LOCALE_STORAGE_KEY), 'zh-CN');
const documentLike = { documentElement: { lang: '' } }; syncDocumentLocale('en-US', documentLike); assert.equal(documentLike.documentElement.lang, 'en-US');
assert.ok(zh.every((key) => key.includes('.')), 'catalog keys must use a namespace');
assert.equal(formatMessage('Hello {name} ({count})', { name: 'Ada', count: 2 }), 'Hello Ada (2)');
assert.equal(resolveMessage('en-US', 'common.loading'), CATALOGS['en-US'].messages['common.loading']);
assert.equal(resolveMessage('en-US', 'missing.test'), 'missing.test');
const i18nEntry = fs.readFileSync(new URL('../src/lib/i18n.tsx', import.meta.url), 'utf8');
assert.equal(/\btext\s*:/.test(i18nEntry), false, 'LocaleValue.text compatibility API must remain removed');
const repo = new InMemoryMessageCatalogRepositoryV1();
await assert.rejects(() => repo.create({ key: 'test.invalidExpected', locale: 'en-US', value: 'Invalid', createdBy: 'test', updatedBy: 'test', expectedRevision: 2 }), /expectedRevision/);
const created = await repo.create({ key: 'test.example', locale: 'en-US', value: 'Example', createdBy: 'test', updatedBy: 'test' });
assert.equal(created.revision, 1);
assert.equal(created.createdAt, created.updatedAt); assert.equal(Number.isNaN(Date.parse(created.createdAt)), false);
await assert.rejects(() => repo.create({ key: 'test.example', locale: 'en-US', value: 'Duplicate', createdBy: 'test', updatedBy: 'test', expectedRevision: 0 }), /already exists/);
const updated = await repo.update('en-US', 'test.example', 'Updated', 'test-2', 1);
assert.equal(updated.revision, 2);
assert.equal((await repo.get('en', 'test.example'))?.value, 'Updated');
await assert.rejects(() => repo.update('en-US', 'test.example', 'Conflict', 'test-3', 1), /revision conflict/);
const archived = await repo.archive('en-US', 'test.example', 'test-2', 2);
assert.equal(archived.status, 'archived');
assert.equal(await repo.get('en-US', 'test.example'), null);
assert.ok(await repo.get('en-US', 'test.example', { includeArchived: true }));
const bundle = new InMemoryMessageCatalogRepositoryV1();
const bundleValues = { 'zh-CN': '你好 {name}', 'en-US': 'Hello {name}' };
const createdBundle = await bundle.createBundle({ key: 'test.bundle', values: bundleValues, actor: 'test' });
assert.equal(createdBundle.length, 2);
await assert.rejects(() => bundle.createBundle({ key: 'test.missingLocale', values: { 'zh-CN': '只有中文' }, actor: 'test' }), /completeness/);
await assert.rejects(() => bundle.createBundle({ key: 'test.badPlaceholders', values: { 'zh-CN': '你好 {name}', 'en-US': 'Hello' }, actor: 'test' }), /placeholder/);
await assert.rejects(() => bundle.updateBundle({ key: 'test.bundle', values: { 'zh-CN': '再见 {name}', 'en-US': 'Bye {name}' }, actor: 'test', expectedRevisions: { 'zh-CN': 99, 'en-US': 1 } }), /revision conflict/);
assert.equal((await bundle.get('zh-CN', 'test.bundle'))?.value, '你好 {name}', 'failed bundle update must not partially write');
const updatedBundle = await bundle.updateBundle({ key: 'test.bundle', values: { 'zh-CN': '再见 {name}', 'en-US': 'Bye {name}' }, actor: 'test', expectedRevisions: { 'zh-CN': 1, 'en-US': 1 } });
assert.equal(updatedBundle.every((entry) => entry.revision === 2), true);
console.log(`i18n checks passed: ${zh.length} keys, parity, interpolation, CRUD/revision/archive`);
