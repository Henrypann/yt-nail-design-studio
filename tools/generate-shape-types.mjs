#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourcePath = path.join(root, 'material-library/shapes/shape-capabilities.json');
const outputPath = path.join(root, 'src/generated/shape-types.ts');
const registry = JSON.parse(await readFile(sourcePath, 'utf8'));
const ids = registry.shapes.map((shape) => shape.id);
const labels = Object.fromEntries(registry.shapes.map((shape) => [shape.id, shape.label]));

const output = `/** AUTO-GENERATED by tools/generate-shape-types.mjs. Do not edit manually. */
export const NAIL_SHAPE_IDS = ${JSON.stringify(ids, null, 2)} as const;

export type NailShape = (typeof NAIL_SHAPE_IDS)[number];

export const NAIL_SHAPE_LABELS: Record<NailShape, string> = ${JSON.stringify(labels, null, 2)};
`;

await writeFile(outputPath, output, 'utf8');
console.log(`[generate-shape-types] wrote ${ids.length} shape ids -> ${path.relative(root, outputPath)}`);
